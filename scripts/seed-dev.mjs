import { webcrypto as crypto } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const opt = (k, d) => {
  const i = args.indexOf(k);
  return i >= 0 ? args[i + 1] : d;
};
const SECRET = opt("--secret", process.env.APP_SECRET || "dev-only-insecure-secret-change-me-0123456789");
const enc = new TextEncoder();
const hex = (b) => [...new Uint8Array(b)].map((x) => x.toString(16).padStart(2, "0")).join("");
const b64 = (b) => Buffer.from(b).toString("base64");

async function hmac(purpose, value) {
  const key = await crypto.subtle.importKey("raw", enc.encode(`${purpose}:${SECRET}`), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  return hex(await crypto.subtle.sign("HMAC", key, enc.encode(value)));
}
async function cipher(code) {
  const raw = await crypto.subtle.digest("SHA-256", enc.encode(`code-cipher:${SECRET}`));
  const key = await crypto.subtle.importKey("raw", raw, { name: "AES-GCM" }, false, ["encrypt"]);
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, enc.encode(code));
  return `${b64(iv)}.${b64(ct)}`;
}
